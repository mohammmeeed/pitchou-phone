export const getCommunesByWilaya = (wilayaQuery) => {
  if (!wilayaQuery) return [];
  const cleanQuery = wilayaQuery.trim().toLowerCase();
  
  const found = ALGERIA_CITIES.find(item => 
    item.name.toLowerCase() === cleanQuery ||
    item.wilaya.toLowerCase() === cleanQuery ||
    cleanQuery.includes(item.wilaya.toLowerCase()) ||
    item.code === cleanQuery
  );

  return found ? found.communes : [];
};
